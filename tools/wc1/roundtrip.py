"""Round-trip proof: emit asm, assemble as flat binary at the original
addresses, compare with the loaded image. Instructions that NASM encodes
differently are demoted to raw bytes and the process repeats until the output
is byte-identical. The demotion list is written to analysis/raw_insns.txt."""
import os
import subprocess
import sys

from . import analysis, emit, path, symbols


def assemble_bin(src, out):
    r = subprocess.run(["nasm", "-O0", "-f", "bin", "-DWC1_FORMAT_BIN", "-I", path("asm") + "/",
                        "-w-number-overflow", "-w+error=label-orphan", "-l", out + ".lst", "-o", out, src],
                       capture_output=True, text=True)
    return r


def main():
    os.makedirs(path("build"), exist_ok=True)
    os.makedirs(path("analysis"), exist_ok=True)
    src, out = path("build", "war_rt.asm"), path("build", "war_rt.bin")
    p = analysis.run()
    code, data = p.le.obj(1), p.le.obj(2)
    want = p.cbytes[:code.vsize] + bytes(p.image[2][:p.data_init_size])
    rawfile = path("analysis", "raw_insns.txt")
    force = set()
    if os.path.exists(rawfile):
        force = {int(l.split()[0], 16) for l in open(rawfile) if l.strip() and not l.startswith("#")}
    # Diagnostic mode: branches as raw bytes keep every size fixed, so the
    # listing exposes all other mis-encoded instructions at once.
    branches = {a for a, i in p.insns.items() if i.mnemonic in analysis.COND_JUMPS | {"jmp", "call"}
                and i.operands and i.operands[0].type == 2}
    names = symbols.label_map()
    diag = True
    for it in range(20):
        e = emit.Emitter(p, names=names, force_raw=force | (branches if diag else set()))
        e.emit(src)
        r = assemble_bin(src, out)
        tag = "diag" if diag else "full"
        if r.returncode != 0:
            bad = set()
            for l in r.stderr.splitlines():
                parts = l.split(":")
                if len(parts) > 2 and parts[1].isdigit() and "error" in l:
                    a = e.line_addr.get(int(parts[1]))
                    if a is not None:
                        bad.add(a)
            print(f"iter {it} [{tag}]: assembler errors, demoting {len(bad)}")
            if not bad:
                print(r.stderr[:2000])
                sys.exit(1)
            force |= bad
            continue
        got = open(out, "rb").read()
        lst = parse_listing(out + ".lst")
        by_insn = {}
        for ln, bs in lst.items():
            a = e.line_addr.get(ln)
            if a is not None:
                by_insn.setdefault(a, []).append((ln, bs))
        bad = set()
        for a, parts in by_insn.items():
            bs = b"".join(x for _, x in sorted(parts))
            if len(bs) != p.insns[a].size or not same_mod_fixups(bs, p, a):
                bad.add(a)
        ok = got == want
        print(f"iter {it} [{tag}]: mismatching insns={len(bad)} image_identical={ok}")
        force |= bad
        if bad:
            continue
        if diag:
            diag = False
            continue
        if ok:
            break
        k = next((k for k in range(min(len(got), len(want))) if got[k] != want[k]), None)
        print(f"image differs at offset {k} (len {len(got)} vs {len(want)})")
        sys.exit(1)
    else:
        print("did not converge")
        sys.exit(1)
    with open(rawfile, "w") as f:
        f.write("# Instructions emitted as raw bytes because NASM picks a different encoding.\n")
        f.write("# Generated by `python3 -m wc1.roundtrip`.\n")
        for a in sorted(force):
            i = p.insns[a]
            f.write(f"{a:05x} {i.mnemonic} {i.op_str}\n")
    print(f"ROUND-TRIP OK: {len(force)} raw instructions of {len(p.insns)}")


def parse_listing(lst):
    """NASM listing -> {source line: bytes}. Bytes still to be relocated
    are shown in brackets/parentheses; we keep their placeholder values."""
    import re
    out = {}
    rx = re.compile(r"^\s*(\d+)\s+[0-9A-F]{8}\s+([0-9A-F\[\]\(\)]+?)(-?)\s")
    last = None
    for line in open(lst, errors="replace"):
        if "<" in line[:40] and ">" in line[:40]:
            continue  # line from an included file or macro expansion
        m = rx.match(line)
        if not m:
            continue
        ln = int(m.group(1))
        hx = re.sub(r"[\[\]\(\)]", "", m.group(2))
        if len(hx) % 2:
            continue
        bs = bytes.fromhex(hx)
        if line.lstrip().startswith(str(ln)) and ln in out and last == ln:
            out[ln] += bs
        else:
            out[ln] = out.get(ln, b"") + bs
        last = ln
    return out


def same_mod_fixups(bs, p, a):
    """Compare listed bytes with the original insn, ignoring fixup fields
    and relative branch displacements (whose final values are checked by the
    whole-image comparison)."""
    i = p.insns[a]
    want = bytearray(i.bytes)
    got = bytearray(bs)
    for k in range(i.size):
        if a + k in p.fix_at:
            for j in range(4):
                if k + j < i.size:
                    want[k + j] = got[k + j] = 0
    if i.mnemonic in analysis.COND_JUMPS | {"jmp", "call"} and i.operands and \
            i.operands[0].type == 2:
        n = 1 if i.size == 2 or i.mnemonic.startswith("loop") or i.mnemonic.startswith("jecxz") else 4
        for j in range(i.size - n, i.size):
            want[j] = got[j] = 0
    return want == got


if __name__ == "__main__":
    main()
