"""Generate a self-contained, token-budgeted dossier for one module or address list.

Replaces repetitive wc1.func / wc1.xref / grep exploration turns with one
structured packet containing:
  - module metadata and auto-detected Watcom 10.0a codegen style/flags
  - per-function symbolic disassembly (wc1.emit)
  - Ghidra decompilation draft from build/ghidra/decomp/ (HINT ONLY, never evidence)
  - callers, callees (with known DB prototypes), referenced data symbols & ASCII strings
  - compact matched 10.0a exemplars for the same compiler style

usage: python3 -m wc1.dossier <module|0xADDR ...> [--only-undone] [--only-missing-c]
                              [--max-funcs N] [--format md|json] [--out FILE]
                              [--no-ghidra] [--no-exemplars]
"""
import argparse
import bisect
import collections
import glob
import json
import os
import sys

from capstone import x86

from . import analysis, codegen_survey, emit, match, path, progress, symbols

STYLE_FLAGS = {
    "OPT": "-s -ot -ol -4r -zp2",
    "DBG": "-s -ot -ol -4r -d1+ -zp2",
    "OD":  "-s -od -4r -zp2",
}


def _ascii_preview(p, addr, maxlen=64):
    """If addr points into initialized data/code and looks like a C string, return it."""
    o = p.le.obj_at(addr)
    if o is None:
        return None
    img = p.image[o.index]
    off = addr - o.base
    if off < 0 or off >= len(img):
        return None
    raw = bytes(img[off:off + maxlen])
    nul = raw.find(0)
    if nul == -1:
        nul = len(raw)
    s = raw[:nul]
    if len(s) >= 3 and all(32 <= b < 127 or b in (9, 10, 13) for b in s):
        return s.decode("ascii", errors="replace")
    return None


def _hex_preview(p, addr, n=16):
    o = p.le.obj_at(addr)
    if o is None:
        return None
    img = p.image[o.index]
    off = addr - o.base
    if off < 0 or off >= len(img):
        return None
    return bytes(img[off:off + n]).hex()


def _ghidra_draft(addr):
    pat = path("build", "ghidra", "decomp", f"{addr:05x}_*.c")
    hits = sorted(glob.glob(pat))
    if not hits:
        return None
    with open(hits[0], errors="replace") as fh:
        lines = fh.readlines()
    # Strip the 2-line generator header to save tokens
    body = [ln for ln in lines if not ln.startswith("/* Ghidra decompiler hint")
            and not ln.startswith("/* Generated by tools/ghidra/")]
    return "".join(body).strip()


def _func_asm(p, emitter, f):
    lines = []
    x = f["start"]
    while x < f["limit"]:
        if x in emitter.labels:
            lines.append(f"{emitter.labels[x]}:")
        if x in p.insns:
            i = p.insns[x]
            t = emitter.insn_text(i) or f"{i.mnemonic} {i.op_str}"
            lines.append(f"  {x:05x}  {t}")
            x += i.size
        elif x in p.fix_at:
            lines.append(f"  {x:05x}  dd {emitter.sym(p.fix_at[x][1])}")
            x += 4
        else:
            y = x
            while (y < f["limit"] and y not in p.insns and y not in p.fix_at
                   and (y == x or y not in emitter.labels)):
                y += 1
            lines.append(f"  {x:05x}  db {p.cbytes[x - p.code.base:y - p.code.base].hex()}")
            x = y
    return "\n".join(lines)


def _build_xref_index(p):
    """Precompute callers & data/ptr refs for every function in one O(N) pass."""
    starts = [f["start"] for f in p.functions]
    callers = collections.defaultdict(set)
    callees = collections.defaultdict(set)
    ptr_from = collections.defaultdict(set)
    refs_out = collections.defaultdict(set)

    def owner_fn(a):
        if not p.in_code(a):
            return None
        k = bisect.bisect_right(starts, a) - 1
        return starts[k] if k >= 0 else None

    for ia, i in p.insns.items():
        if i.mnemonic in analysis.COND_JUMPS | {"jmp", "call"} and i.operands and \
                i.operands[0].type == x86.X86_OP_IMM:
            t = i.operands[0].imm & 0xFFFFFFFF
            src_fn = owner_fn(ia)
            if src_fn is not None and src_fn != t:
                callers[t].add(src_fn)
                if i.mnemonic == "call":
                    callees[src_fn].add(t)
    for s, (_fx, t) in p.fix_at.items():
        src_fn = owner_fn(s)
        if src_fn is not None:
            refs_out[src_fn].add(t)
            if p.in_code(t):
                ptr_from[t].add(src_fn)
        elif p.in_code(t):
            ptr_from[t].add(("data", s))
    return callers, callees, ptr_from, refs_out


def _pick_exemplars(funcs_db, style, count=2):
    """Pick `count` short (<35 lines) already-matched 10.0a C files for `style`."""
    want_od = (style == "OD")
    want_dbg = (style == "DBG")
    cands = []
    seen = set()
    for e in sorted(funcs_db.values(), key=lambda x: x["addr"]):
        src = e.get("src")
        if not src or src in seen:
            continue
        seen.add(src)
        full = path(src)
        if not os.path.isfile(full):
            continue
        if match.file_cc(full) != "10.0a":
            continue
        flags = match.file_cflags(full)
        is_od = "-od" in flags
        is_dbg = "-d1+" in flags
        if is_od != want_od or (not want_od and is_dbg != want_dbg):
            continue
        text = open(full, errors="replace").read()
        nlines = text.count("\n")
        if 8 <= nlines <= 35:
            cands.append((nlines, src, text.strip()))
            if len(cands) >= count:
                break
    return [{"path": s, "source": t} for _n, s, t in cands]


def build_dossier(targets, only_undone=False, only_missing_c=False,
                  max_funcs=None, include_ghidra=True, include_exemplars=True):
    """Build a structured dossier dict for a module name or hex addresses."""
    p = analysis.run()
    funcs_db, datas_db, _errs = symbols.load(strict=False)
    mods = progress.load_modules()
    rows = progress.classify([f["start"] for f in p.functions], funcs_db, mods)
    row_by_addr = {r["addr"]: r for r in rows}
    f_by_start = {f["start"]: f for f in p.functions}
    mod_by_name = {m["name"]: m for m in mods}

    selected_addrs = []
    mod_info = None
    for t in targets:
        if t in mod_by_name:
            mod_info = mod_by_name[t]
            selected_addrs.extend(
                r["addr"] for r in rows if r["module"] == t and r["scope"] == "in"
            )
        else:
            try:
                a = int(t, 16)
            except ValueError:
                # Try symbol name lookup
                hit = next((addr for addr, e in funcs_db.items() if e["name"] == t), None)
                if hit is None:
                    raise SystemExit(f"unknown module or function: {t}")
                a = hit
            if a not in f_by_start:
                raise SystemExit(f"{a:#x} is not a discovered function start")
            selected_addrs.append(a)

    # Deduplicate preserving order
    selected_addrs = list(dict.fromkeys(selected_addrs))
    if only_undone:
        selected_addrs = [a for a in selected_addrs if not row_by_addr[a]["done"]]
    if only_missing_c:
        selected_addrs = [a for a in selected_addrs if row_by_addr[a]["c"] == "none"]
    if max_funcs is not None:
        selected_addrs = selected_addrs[:max_funcs]

    names = {e["addr"]: e["link_name"] for t in (datas_db, funcs_db) for e in t.values()}
    emitter = emit.Emitter(p, names=names)
    callers_idx, callees_idx, ptr_idx, refs_idx = _build_xref_index(p)

    # Detect dominant codegen style across selected functions
    styles = collections.Counter()
    fn_entries = []
    for a in selected_addrs:
        f = f_by_start[a]
        ft = codegen_survey.feat(p, f)
        if not (ft["style"] == "OPT" and ft["size"] <= 12):
            styles[ft["style"]] += 1
        meta = funcs_db.get(a)
        r = row_by_addr[a]

        def fmt_fn(addr):
            e = funcs_db.get(addr)
            if e:
                return {"addr": f"{addr:#x}", "name": e["name"], "proto": e.get("proto", "")}
            return {"addr": f"{addr:#x}", "name": f"fn_{addr:05x}", "proto": ""}

        c_in = sorted(callers_idx.get(a, set()))[:10]
        c_out = sorted(callees_idx.get(a, set()))
        p_in = []
        for x in sorted(ptr_idx.get(a, set()), key=lambda v: (isinstance(v, tuple), str(v)))[:6]:
            if isinstance(x, tuple):
                p_in.append(f"data@{x[1]:#x}")
            else:
                e = funcs_db.get(x)
                p_in.append(e["name"] if e else f"fn_{x:05x}")

        data_refs = []
        for da in sorted(refs_idx.get(a, set())):
            if p.in_code(da):
                continue
            de = datas_db.get(da)
            item = {
                "addr": f"{da:#x}",
                "name": de["name"] if de else f"dat_{da:05x}",
                "type": de.get("type", "") if de else "",
            }
            s_prev = _ascii_preview(p, da)
            if s_prev is not None:
                item["ascii"] = s_prev
            elif not de:
                h_prev = _hex_preview(p, da, 12)
                if h_prev:
                    item["hex"] = h_prev
            data_refs.append(item)

        fn_entries.append({
            "addr": f"{a:#x}",
            "addr_int": a,
            "end": f"{f['end']:#x}",
            "limit": f"{f['limit']:#x}",
            "ninsns": f["ninsns"],
            "module": r["module"],
            "style": ft["style"],
            "done": r["done"],
            "missing": r["missing"],
            "existing": {
                "name": meta["name"],
                "proto": meta.get("proto", ""),
                "confidence": meta["confidence"],
                "conv": meta.get("conv", "watcall"),
                "src": meta.get("src"),
                "ref": meta.get("ref"),
                "file": meta.get("_file"),
            } if meta else None,
            "callers": [fmt_fn(x) for x in c_in],
            "ptr_refs": p_in,
            "callees": [fmt_fn(x) for x in c_out],
            "data_refs": data_refs,
            "asm": _func_asm(p, emitter, f),
            "ghidra_hint": _ghidra_draft(a) if include_ghidra else None,
        })

    dom_style = styles.most_common(1)[0][0] if styles else "OPT"
    rec_flags = STYLE_FLAGS.get(dom_style, STYLE_FLAGS["OPT"])
    exemplars = _pick_exemplars(funcs_db, dom_style, count=2) if include_exemplars else []

    return {
        "targets": targets,
        "module": mod_info["name"] if mod_info else (fn_entries[0]["module"] if fn_entries else "?"),
        "range": [f"{mod_info['start']:#x}", f"{mod_info['end']:#x}"] if mod_info else None,
        "dominant_style": dom_style,
        "recommended_cflags": rec_flags,
        "compiler": "10.0a",
        "function_count": len(fn_entries),
        "total_insns": sum(x["ninsns"] for x in fn_entries),
        "exemplars": exemplars,
        "functions": fn_entries,
    }


def render_markdown(d):
    out = [
        f"# Dossier: {d['module']} ({d['function_count']} functions, {d['total_insns']} insns)",
        "",
        f"- Compiler: `/* codegen-compiler: {d['compiler']} */` (OW2 compile-check required)",
        f"- Detected style: `{d['dominant_style']}` → default flags `{d['recommended_cflags']}`",
    ]
    if d["range"]:
        out.append(f"- Module range: `{d['range'][0]}..{d['range'][1]}`")
    out.append("- Rule: Ghidra drafts below are **structural hints only — never cite Ghidra in TOML `evidence`**.")
    out.append("")

    if d["exemplars"]:
        out.append("## Matched 10.0a Exemplars")
        for ex in d["exemplars"]:
            out.append(f"### `{ex['path']}`")
            out.append("```c")
            out.append(ex["source"])
            out.append("```")
        out.append("")

    out.append("## Functions")
    for fn in d["functions"]:
        ex = fn["existing"]
        hdr_name = ex["name"] if ex else f"fn_{fn['addr_int']:05x}"
        out.append(f"### {hdr_name} (`{fn['addr']}..{fn['end']}`, {fn['ninsns']} insns, style `{fn['style']}`)")
        if ex:
            out.append(f"- Existing DB (`{ex['file']}`): `{ex['proto'] or ex['name']}` [{ex['confidence']}] missing={fn['missing']}")
        if fn["callers"]:
            out.append("- Callers: " + ", ".join(
                f"`{c['name']}` ({c['addr']})" for c in fn["callers"]))
        if fn["ptr_refs"]:
            out.append("- Pointer refs: " + ", ".join(f"`{x}`" for x in fn["ptr_refs"]))
        if fn["callees"]:
            out.append("- Callees: " + ", ".join(
                f"`{c['proto'] or c['name']}` ({c['addr']})" for c in fn["callees"]))
        if fn["data_refs"]:
            dparts = []
            for dr in fn["data_refs"]:
                s = f"`{dr['name']}` ({dr['addr']}"
                if dr["type"]:
                    s += f", {dr['type']}"
                if "ascii" in dr:
                    s += f", str={dr['ascii']!r}"
                elif "hex" in dr:
                    s += f", hex={dr['hex']}"
                s += ")"
                dparts.append(s)
            out.append("- Data refs: " + ", ".join(dparts))
        out.append("```asm")
        out.append(fn["asm"])
        out.append("```")
        if fn["ghidra_hint"]:
            out.append("```c")
            out.append("/* GHIDRA HINT ONLY — DO NOT CITE AS EVIDENCE */")
            out.append(fn["ghidra_hint"])
            out.append("```")
        out.append("")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="wc1.dossier", description=__doc__.split("\n\n")[0])
    ap.add_argument("targets", nargs="+", help="module name(s) from analysis/modules.toml or hex address(es)")
    ap.add_argument("--only-undone", action="store_true")
    ap.add_argument("--only-missing-c", action="store_true")
    ap.add_argument("--max-funcs", type=int, default=None)
    ap.add_argument("--format", choices=("md", "json"), default="md")
    ap.add_argument("--out", default=None, help="write output to file instead of stdout")
    ap.add_argument("--no-ghidra", action="store_true")
    ap.add_argument("--no-exemplars", action="store_true")
    a = ap.parse_args(argv)
    d = build_dossier(
        a.targets,
        only_undone=a.only_undone,
        only_missing_c=a.only_missing_c,
        max_funcs=a.max_funcs,
        include_ghidra=not a.no_ghidra,
        include_exemplars=not a.no_exemplars,
    )
    text = json.dumps(d, indent=1) if a.format == "json" else render_markdown(d)
    if a.out:
        os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
        with open(a.out, "w") as fh:
            fh.write(text + ("\n" if not text.endswith("\n") else ""))
        print(f"wrote {a.out} ({d['function_count']} functions, {d['total_insns']} insns, {len(text)} chars)")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
