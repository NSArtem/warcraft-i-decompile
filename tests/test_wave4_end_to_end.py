"""Exercise the real Wave 4 CLI and verification in a disposable Git repo."""
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import tomllib

import pytest

from wc1 import oldcc, path


REF = "src/cmd_123f0/fog_map_clear_reference.c"
TOML = "analysis/symbols/cmd.toml"
BEFORE = "    unsigned short *p = fog_map;\n    unsigned short i;"
AFTER = "    unsigned short i;\n    register unsigned short *p = fog_map;"
SOURCE = f"""/* codegen-flags: -s -ot -oa -4r -zp2
 * codegen-compiler: ow2
 * Historical FogMapClear near miss.
 */
extern unsigned short *fog_map;
void FogMapClear(void)
{{
{BEFORE}
    for (i = 0; i < 0x1000; i++)
        *p++ = 0;
}}
"""
SYMBOLS = f"""[[func]]
addr = 0x12404
name = "FogMapClear"
conv = "watcall"
proto = "void FogMapClear(void)"
module = "CMD.C"
confidence = "high"
ref = "{REF}"
ref_verified_by = "difftest: tests/test_fixture.py::test_reference"
t3_blocker = "regalloc: the loop keeps fog_map in a different register"
evidence = ["original function at 0x12404"]

[[data]]
addr = 0x58578
name = "fog_map"
type = "unsigned short *"
confidence = "high"
evidence = ["original fog_map at 0x58578"]
"""
DIFFTEST = f"""from wc1 import cemu, match, path
from wc1.emu import Emu


def test_reference():
    emu = Emu()
    src = path("{REF}")
    mod = cemu.load(emu, src)
    buf = emu.alloc(0x2008)
    emu.write(buf, b"\\xff" * 0x2008)
    emu.put_u32(0x58578, buf)
    assert not cemu.run_pair(emu, 0x12404, mod, "FogMapClear_", watch=[(buf, 0x2008)], out_regs=())
    with open(path("build", "difftest-compilers"), "a") as fh:
        print(match.file_cc(src), file=fh)
"""


def setup_repo(repo, gate):
    def write(name, text):
        fn = repo / name
        fn.parent.mkdir(parents=True, exist_ok=True)
        fn.write_text(text)
        return fn

    def git(*args):
        return subprocess.check_output(["git", *args], cwd=repo, text=True).strip()

    for name in ("Makefile", "asm/wc1.inc", "analysis/modules.toml", "analysis/raw_insns.txt",
                 "analysis/provenance/watcom10a.sha256"):
        (repo / name).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path(name), repo / name)
    original = repo / "original/install/war.exe"
    original.parent.mkdir(parents=True)
    original.symlink_to(path("original", "install", "war.exe"))
    write(".gitignore", "/build/\n/original/\n__pycache__/\n.pytest_cache/\n")
    write(REF, SOURCE)
    write(TOML, SYMBOLS)
    test_extra = ""
    if gate == "verify":
        test_extra = ('\n\ndef test_full_gate():\n'
                      '    with open("verification-stray.txt", "w") as fh:\n'
                      '        fh.write("unexpected verification artifact")\n'
                      '    assert False, "controlled full-gate failure"\n')
    write("tests/test_fixture.py", DIFFTEST + test_extra)
    git("init", "-q")
    git("config", "user.name", "Wave 4 fixture")
    git("config", "user.email", "wave4@example.test")
    git("config", "commit.gpgsign", "false")
    git("config", "core.hooksPath", ".git/hooks")
    git("add", "--", ".gitignore", "Makefile", "asm", "analysis", "src", "tests")
    git("commit", "-qm", "T4 fixture")
    if gate == "commit":
        write(".git/hooks/pre-commit", "#!/bin/sh\nexit 1\n").chmod(0o755)

    # Stub only the model response, through the real provider protocol. The
    # runner/driver subprocesses, audit, compiler, make and Git are unchanged.
    payload = {"type": "result", "structured_output": {
        "diagnosis": "recover the register assignment", "patches": [{"old": BEFORE, "new": AFTER}],
    }}
    model = write("build/fake-bin/claude", f"""#!/usr/bin/env python3
import sys
from pathlib import Path
Path("build/model.prompt").write_text(sys.stdin.read())
print({json.dumps(payload)!r})
""")
    model.chmod(0o755)
    return git, model.parent


@pytest.fixture
def short_repo():
    # Watcom 10.0a can crash on the long paths generated by nested xdist.
    base = "/tmp/opencode" if os.path.isdir("/tmp/opencode") else "/tmp"
    with tempfile.TemporaryDirectory(prefix="w4-", dir=base) as directory:
        yield Path(directory)


@pytest.mark.parametrize("gate", [None, "verify", "commit"])
def test_actual_wave4_recovery_with_full_gate_and_git(short_repo, gate):
    if not (Path(path("original/install/war.exe")).is_file() and os.environ.get("WATCOM")
            and all(shutil.which(cmd) for cmd in ("git", "make", "nasm", "wlink", "wine"))):
        pytest.skip("requires original game and Nix dev toolchains")
    try:
        watcom = oldcc.require()
    except oldcc.OldCCError:
        pytest.skip("requires Watcom 10.0a (make toolchain)")
    repo = short_repo
    git, fake_bin = setup_repo(repo, gate)
    head = git("rev-parse", "HEAD")
    env = dict(os.environ, WC1_ROOT=str(repo), WC1_WATCOM10A=watcom,
               WINEPREFIX=oldcc.wine_env()["WINEPREFIX"], PYTEST_XDIST_AUTO_NUM_WORKERS="1",
               PATH=f"{fake_bin}{os.pathsep}{os.environ['PATH']}")
    for key in ("PYTEST_XDIST_WORKER", "PYTEST_XDIST_WORKER_COUNT", "PYTEST_XDIST_TESTRUNUID"):
        env.pop(key, None)
    proc = subprocess.run(
        [sys.executable, "-m", "wc1.overnight", "--headless", "--wave", "wave4", "--only", "0x12404",
         "--max-modules", "1", "--wave4-max-calls", "1", "--window-budget", "1", "--no-sleep"],
        cwd=repo, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=180,
    )
    out = proc.stdout
    assert (proc.returncode != 0) == (gate == "commit"), out
    receipt = json.loads((repo / "build/wave4/outcomes/12404.json").read_text())
    state = json.loads((repo / "build/live/state.json").read_text())
    assert receipt["history"][0]["status"] == "MISMATCH", receipt
    assert receipt["history"][1]["status"] == "MATCH_BUILDABLE", receipt
    assert receipt["outcome"] == "PROMOTED" and receipt["promoted"] == ["0x12404"], receipt
    assert receipt["llm_calls"] == 1 and receipt["history"][1]["diagnosis"] == "recover the register assignment"
    assert "first difference:" in (repo / "build/model.prompt").read_text()
    assert (repo / "build/difftest-compilers").read_text().splitlines() == ["10.0a", "10.0a"], out
    assert "built" in out and "IDENTICAL (loaded image, entry, stack, fixups)" in out, out
    assert "compile check: 1 files x 2 compilers, 0 failures" in out, out
    assert not git("status", "--porcelain"), out
    if gate is None:
        assert git("rev-parse", "HEAD^") == head and "[COMMITTED " in out
        assert set(git("diff-tree", "--no-commit-id", "--name-only", "-r", "HEAD").splitlines()) == {REF, TOML}
        promotion = state["completed"][0]
        assert promotion["status"] == "COMMITTED" and promotion["delta"] == 1
        func, = tomllib.loads((repo / TOML).read_text())["func"]
        assert func["src"] == REF and "ref" not in func and "ref_verified_by" not in func
        assert func["verified_by"].startswith("match:") and func["confidence"] == "verified"
        assert "original function at 0x12404" in func["evidence"]
        assert AFTER in (repo / REF).read_text()
    else:
        assert git("rev-parse", "HEAD") == head and "[COMMITTED " not in out
        assert (repo / REF).read_text() == SOURCE and (repo / TOML).read_text() == SYMBOLS
        archived, = (repo / "build/failed").glob("*_w4_12404")
        assert AFTER in (archived / REF).read_text()
        assert tomllib.loads((archived / TOML).read_text())["func"][0]["src"] == REF
        failure = (archived / "failure.log").read_text()
        if gate == "verify":
            assert state["completed"][0]["status"] == "FAILED"
            assert "controlled full-gate failure" in failure
            assert (archived / "verification-stray.txt").read_text() == "unexpected verification artifact"
        else:
            assert state["status"] == "FAILED"
            assert "git" in failure and "commit" in failure
