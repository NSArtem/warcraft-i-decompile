"""Ghidra decompiler hints for war.exe (see docs/ANALYST_GUIDE.md).

Ghidra output is a HINT only, never evidence: nothing here writes to
analysis/symbols/. The exporter imports the *loaded* code and data objects
(LE fixups already applied, see wc1.analysis) as raw binaries, because Ghidra
has no LE loader.

Commands:
  python3 -m wc1.ghidra_decomp prepare        write build/ghidra/input/
  python3 -m wc1.ghidra_decomp run            prepare + headless Ghidra + summary
  python3 -m wc1.ghidra_decomp summary        counts from build/ghidra/decomp/index.tsv
  python3 -m wc1.ghidra_decomp show <addr|name>

Outputs (all under build/ghidra/):
  input/code.bin, input/data.bin   loaded objects 1 (code) and 2 (data, incl. BSS)
  input/meta.json                  bases, sizes, functions, names, fixup sites
  input/meta.txt                   the same, line format read by tools/ghidra/WcDecomp.java
  project/                         Ghidra project (recreated on every run)
  decomp/<start:05x>_<name>.c      decompiled C per function
  decomp/index.tsv                 start, end, name, status (ok|timeout|error)
  ghidra.log                       full analyzeHeadless output
"""
import csv
import json
import os
import re
import shutil
import subprocess
import sys
import time

from . import analysis
from . import path
from . import symbols as dbsyms

BUILD = path("build", "ghidra")
INPUT = os.path.join(BUILD, "input")
PROJECT = os.path.join(BUILD, "project")
DECOMP = os.path.join(BUILD, "decomp")
JAVA_SCRIPT = path("tools", "ghidra", "WcDecomp.java")
PROJ_NAME = "wc1"
LANGUAGE = "x86:LE:32:default"
TIMEOUT_SECS = 60
CODE_FILE, DATA_FILE = "code.bin", "data.bin"
# fixup source types of 4-byte absolute pointers (wc1.le SRC_PTR1632, SRC_OFF32)
POINTER_SRC_TYPES = {6, 7}


def analyze_headless():
    """Path of analyzeHeadless: <dir of ghidra launcher>/support/analyzeHeadless."""
    exe = shutil.which("ghidra")
    if exe is None:
        raise SystemExit("ghidra not found on PATH (run inside `nix develop`)")
    home = os.path.dirname(os.path.realpath(exe))
    for cand in (os.path.join(home, "support", "analyzeHeadless"),
                 os.path.join(home, "..", "support", "analyzeHeadless"),
                 os.path.join(home, "..", "lib", "ghidra", "support", "analyzeHeadless")):
        if os.path.exists(cand):
            return os.path.realpath(cand)
    raise SystemExit(f"analyzeHeadless not found next to {exe}")


def fn_name(start, db_funcs):
    e = db_funcs.get(start)
    if e is not None:
        return e["name"]
    return f"fn_{start:x}"


def safe_name(name):
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def prepare(verbose=True):
    """Write build/ghidra/input/. Returns the metadata dict."""
    p = analysis.run()
    db_funcs, db_datas, _ = dbsyms.load()
    code, data = p.code, p.data
    code_bytes = bytes(p.image[code.index][:code.vsize])
    data_bytes = bytes(p.image[data.index][:data.vsize])
    assert len(code_bytes) == code.vsize and len(data_bytes) == data.vsize

    os.makedirs(INPUT, exist_ok=True)
    with open(os.path.join(INPUT, CODE_FILE), "wb") as fh:
        fh.write(code_bytes)
    with open(os.path.join(INPUT, DATA_FILE), "wb") as fh:
        fh.write(data_bytes)

    functions = []
    for f in p.functions:
        s = f["start"]
        functions.append({"start": s, "end": f["end"], "name": fn_name(s, db_funcs),
                          "named": s in db_funcs})
    functions.sort(key=lambda f: f["start"])
    names_seen = {}
    for f in functions:
        if f["name"] in names_seen:
            raise SystemExit(f"duplicate function name {f['name']}")
        names_seen[f["name"]] = f["start"]

    data_symbols = []
    skipped = 0
    for a, e in sorted(db_datas.items()):
        if data.base <= a < data.end:
            data_symbols.append({"addr": a, "name": e["name"]})
        else:
            skipped += 1

    fixups = []
    fixup_lines = []
    for site, (f, tgt) in sorted(p.fix_at.items()):
        fixups.append([site, tgt])
        if data.base <= site < data.end:
            fixup_lines.append(f"P {site:x} {tgt:x} {f.size}")

    meta = {
        "language": LANGUAGE,
        "entry": p.le.entry,
        "code": {"base": code.base, "size": code.vsize, "file": CODE_FILE},
        "data": {"base": data.base, "size": data.vsize, "file": DATA_FILE,
                 "init_size": p.data_init_size},
        "functions": functions,
        "data_symbols": data_symbols,
        "fixups": fixups,
        "fixups_in_data": len(fixup_lines),
    }
    with open(os.path.join(INPUT, "meta.json"), "w") as fh:
        json.dump(meta, fh, indent=1)
        fh.write("\n")

    # Line format for the Java side (names have no spaces; hex without 0x).
    lines = ["# wc1 ghidra meta (generated by wc1.ghidra_decomp prepare)",
             f"CODE {code.base:x} {code.vsize:x} {CODE_FILE}",
             f"DATA {data.base:x} {data.vsize:x} {DATA_FILE}"]
    lines += [f"F {f['start']:x} {f['end']:x} {f['name']}" for f in functions]
    lines += [f"D {d['addr']:x} {d['name']}" for d in data_symbols]
    lines += fixup_lines
    with open(os.path.join(INPUT, "meta.txt"), "w") as fh:
        fh.write("\n".join(lines) + "\n")

    if verbose:
        print(f"code.bin {len(code_bytes)} bytes at {code.base:#x}, "
              f"data.bin {len(data_bytes)} bytes at {data.base:#x}")
        print(f"functions {len(functions)} (named in DB: "
              f"{sum(f['named'] for f in functions)}), data symbols {len(data_symbols)} "
              f"(outside data object, skipped: {skipped}), fixups {len(fixups)} "
              f"(in data object: {len(fixup_lines)})")
    return meta


def run_headless(log_path):
    exe = analyze_headless()
    if os.path.isdir(PROJECT):
        shutil.rmtree(PROJECT)
    os.makedirs(PROJECT, exist_ok=True)
    if os.path.isdir(DECOMP):
        shutil.rmtree(DECOMP)
    os.makedirs(DECOMP, exist_ok=True)
    cmd = [exe, PROJECT, PROJ_NAME,
           "-import", os.path.join(INPUT, CODE_FILE),
           "-loader", "BinaryLoader", "-loader-baseAddr", f"{0x10000:#x}",
           "-processor", LANGUAGE,
           "-overwrite", "-noanalysis",
           "-scriptPath", os.path.dirname(JAVA_SCRIPT),
           "-postScript", os.path.basename(JAVA_SCRIPT), INPUT, DECOMP]
    t0 = time.time()
    with open(log_path, "w") as log:
        proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                text=True, errors="replace")
        for line in proc.stdout:
            log.write(line)
        rc = proc.wait()
    elapsed = time.time() - t0
    return rc, elapsed


def read_index():
    idx = os.path.join(DECOMP, "index.tsv")
    if not os.path.exists(idx):
        return []
    with open(idx, newline="") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def summary():
    rows = read_index()
    counts = {}
    for r in rows:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    total = len(rows)
    ok = counts.get("ok", 0)
    print(f"functions {total}: ok {ok}, timeout {counts.get('timeout', 0)}, "
          f"error {counts.get('error', 0)}, other {total - sum(counts.get(k, 0) for k in ('ok', 'timeout', 'error'))}")
    if total:
        print(f"ok fraction {ok / total:.1%}")
    return counts


def run():
    os.makedirs(BUILD, exist_ok=True)
    prepare()
    log_path = os.path.join(BUILD, "ghidra.log")
    rc, elapsed = run_headless(log_path)
    print(f"analyzeHeadless exit code {rc}, elapsed {elapsed:.0f} s, log {log_path}")
    summary()
    return rc


def _resolve(query):
    """Function start for an address (0x1d7cc, fn_1d7cc, 1d7cc) or a function name."""
    q = query.strip()
    m = re.fullmatch(r"(?:fn_|0x)([0-9a-fA-F]+)|([0-9a-fA-F]{5,6})", q)
    if m:
        return int(m.group(1) or m.group(2), 16)
    db_funcs, _, _ = dbsyms.load()
    for a, e in db_funcs.items():
        if q in (e["name"], e["link_name"]):
            return a
    for r in read_index():
        if r["name"] == q:
            return int(r["start"], 16)
    raise SystemExit(f"cannot resolve {query!r} to a function")


def show(query):
    start = _resolve(query)
    prefix = f"{start:05x}_"
    rows = {int(r["start"], 16): r for r in read_index()}
    r = rows.get(start)
    if r is None:
        raise SystemExit(f"{start:#x} is not a function in the export (run `run` first)")
    if r["status"] != "ok":
        print(f"{start:#x} {r['name']}: status {r['status']} (no decompiled file)")
        return 1
    fname = next((f for f in os.listdir(DECOMP) if f.startswith(prefix) and f.endswith(".c")), None)
    if fname is None:
        raise SystemExit(f"status ok but no file for {start:#x} in {DECOMP}")
    with open(os.path.join(DECOMP, fname), encoding="utf-8") as fh:
        sys.stdout.write(fh.read())
    return 0


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] not in ("prepare", "run", "summary", "show"):
        print(__doc__)
        return 2
    cmd = argv[0]
    if cmd == "prepare":
        prepare()
        return 0
    if cmd == "run":
        return run()
    if cmd == "summary":
        summary()
        return 0
    if len(argv) != 2:
        print("usage: python3 -m wc1.ghidra_decomp show <addr|name>")
        return 2
    return show(argv[1])


if __name__ == "__main__":
    sys.exit(main())
