"""Reproducible real-object mutations and independent boundary fixtures for E0.

No copyrighted object/image fixture is persisted in the repository. All real
fixtures compile existing C; pointer-table bytes are read from the supplied EXE.
Synthetic modules use the same omf.Module/Segment/Fixup types as parsed objects.
"""
from copy import deepcopy
from dataclasses import dataclass
from pathlib import Path
import struct
from types import SimpleNamespace

import capstone
from wc1 import analysis, le, match, omf, path
from .matcher_proto import OriginalIndex, load_inputs, match_module


@dataclass
class Control:
    id: str
    description: str
    p: object
    mod: object
    db: dict
    expected: str
    required_categories: tuple = ()
    required_codes: tuple = ()
    expected_function: str | None = None
    provenance: dict | None = None


def _set32(buf, off, value):
    struct.pack_into("<I", buf, off, value & 0xffffffff)


def synthetic(code, fixups=(), *, fn_end=None, publics=None, original=None,
              original_fixes=()):
    """An independent in-memory original image, not generated by the matcher."""
    base = 0x10000
    raw = original if original is not None else code
    obj = le.Obj(1, len(raw), base, le.OBJ_READ | le.OBJ_EXEC, 1, 1)
    obj_at = lambda a: obj if obj.base <= a < obj.end else None
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    insns = {i.address: i for i in md.disasm(raw, base)}
    starts = sorted({off for si, off in (publics or {"Probe_": (1, 0)}).values() if si == 1})
    functions = [dict(start=base+off, end=base+(starts[k+1] if k+1 < len(starts)
                                             else (fn_end or len(raw))))
                 for k, off in enumerate(starts)]
    p = SimpleNamespace(code=obj, cbytes=raw, image={1: bytearray(raw)},
                        le=SimpleNamespace(obj_at=obj_at),
                        fix_at={base+off: (le.Fixup(1, off, 7, 1, target-base), target)
                                for off, target in original_fixes},
                        insns=insns, functions=functions)
    s = omf.Segment("_TEXT", "CODE", 1, len(code), bytearray(code), list(fixups))
    m = omf.Module("synthetic", [s], publics=publics or {"Probe_": (1, 0)})
    db = {n: dict(addr=base+off, link_name=n) for n, (_, off) in m.publics.items()}
    return p, m, db


def build_controls():
    p, db = load_inputs()
    out = Path(path("build", "e0", "obj", "controls"))
    out.mkdir(parents=True, exist_ok=True)
    def compile_real(src):
        return match.compile_c(path(src), None, str(out / (Path(src).stem+".obj")), quiet=True)

    choose_src = "src/mod_13f60/choose_campaign_dialog.c"
    hardware_src = "src/playflic/intro_op_clear_screen.c"
    init_src = "src/init.c"
    choose, hardware, init = [compile_real(s) for s in (choose_src, hardware_src, init_src)]
    cases = []
    def real(cid, desc, m, expected, cats=(), codes=(), function=None, src=init_src, **prov):
        cases.append(Control(cid, desc, p, m, db, expected, cats, codes, function,
                             dict(source=src, compiler=match.file_cc(path(src)),
                                  cflags=match.file_cflags(path(src)), mutation=desc, **prov)))

    real("P1", "Correct real pre-function switch table", choose, "MATCH",
         function="MATCH", src=choose_src, leading_orig_range=["0x157d8", "0x157e8"])
    bad = deepcopy(choose)
    table = bad.seg("_TEXT")[1]
    assert table.fixups[0].offset < 16
    # Change a table addend, preserving every instruction and the relocation.
    _set32(table.data, table.fixups[0].offset,
           int.from_bytes(table.data[0:4], "little") + 1)
    real("N1", "Leading switch entry resolves one byte beyond original case", bad,
         "MISMATCH", ("code_reloc_forward",), function="MATCH", src=choose_src)
    real("P2", "Real InitPaths absolute OMF and LE obligations", init, "MATCH", function="MATCH")
    absolute = next(f for f in init.seg("_TEXT")[1].fixups if not f.self_rel)
    init_base = db["InitPaths_"]["addr"]
    def hardcode_code(m, offset=None):
        s = m.seg("_TEXT")[1]
        fu = next(f for f in s.fixups if f.offset == (absolute.offset if offset is None else offset))
        s.fixups.remove(fu)
        _set32(s.data, fu.offset, p.fix_at[init_base+fu.offset][1])
    bad = deepcopy(init)
    hardcode_code(bad)
    real("N2", "Exact original code address bytes with OMF FIXUPP stripped", bad,
         "MISMATCH", ("code_reloc_reverse",), ("missing_compiled_absolute_fixup",))
    hs = hardware.seg("_TEXT")[1]
    vga_offset = hs.data.index(struct.pack("<I", 0xa0000))
    vga_addr = db["IntroOpClearScreen_"]["addr"] + vga_offset
    assert not any(f.offset < vga_offset+4 and f.offset+f.size > vga_offset for f in hs.fixups)
    assert not any(a < vga_addr+4 and a+f.size > vga_addr for a, (f, _) in p.fix_at.items())
    real("P3", "Real VGA 0xa0000 constant has neither OMF nor LE fixup", hardware,
         "MATCH", function="MATCH", src=hardware_src, hardware_constant="0xa0000",
         hardware_field_orig_addr=hex(vga_addr), hardware_field_compiled_offset=vga_offset)
    # Table at 0x5159c has real LE code-pointer fixups. Derive a legitimate
    # data anchor from an existing code absolute field, with an explicit addend.
    table_base = 0x5159c
    table_size = 8
    assert all(table_base+j in p.fix_at for j in (0, 4))
    local = deepcopy(init)
    s = local.seg("_TEXT")[1]
    data_si = len(local.segments) + 1
    fu = next(f for f in s.fixups if f.offset == absolute.offset)
    fu.target_kind, fu.target, fu.disp = "seg", data_si, 0
    _set32(s.data, fu.offset, p.fix_at[init_base+fu.offset][1] - table_base)
    data_obj = p.le.obj_at(table_base)
    raw_table = p.image[data_obj.index][table_base-data_obj.base:table_base-data_obj.base+table_size]
    # All targets must be real named addresses, independent of matcher output.
    names_by_addr = {e["addr"]: n for n, e in db.items()}
    pointers = [omf.Fixup(j, 9, False, "ext", names_by_addr[p.fix_at[table_base+j][1]], 0)
                for j in (0, 4)]
    local.segments.append(omf.Segment("CONST", "DATA", 1, 8, bytearray(8), pointers))
    real("P4", "Real EXE two-pointer table in synthetic local CONST segment", local,
         "MATCH", function="MATCH", table_orig_range=[hex(table_base), hex(table_base+8)],
         fixture_kind="real-body-derived OMF module")
    bad = deepcopy(local)
    bad.segments[-1].fixups[0].target = bad.segments[-1].fixups[1].target
    assert pointers[0].target != pointers[1].target
    real("N3", "Wrong local pointer target, hidden by legacy data mask", bad,
         "MISMATCH", ("data_reloc_forward",))
    bad = deepcopy(local)
    bad.segments[-1].fixups.pop(0)
    bad.segments[-1].data[:4] = raw_table[:4]
    real("N4", "Exact original local pointer bytes with OMF FIXUPP stripped", bad,
         "MISMATCH", ("data_reloc_reverse",))
    bad = deepcopy(init)
    next(f for f in bad.seg("_TEXT")[1].fixups if f.offset == absolute.offset).self_rel = True
    real("N5", "Absolute field mislabeled self-relative with identical bytes", bad,
         "MISMATCH", ("code_reloc_forward", "code_reloc_reverse"))
    assert any(f.self_rel and init_base+f.offset not in p.fix_at
               for f in init.seg("_TEXT")[1].fixups)
    real("P5", "Real external rel32 call within CODE_OBJ has no LE loader fixup", init,
         "MATCH", function="MATCH")
    def synth(cid, desc, triple, expected, cats=(), codes=()):
        pp, mm, dd = triple
        cases.append(Control(cid, desc, pp, mm, dd, expected, cats, codes,
                             provenance=dict(fixture_kind="independent synthetic OMF/LE model")))
    synth("N6", "Extent retry cannot discard non-filler tail code",
          synthetic(b"\xc3\x40\xc3", fn_end=1, original=b"\xc3\x90\x90"),
          "MISMATCH", ("extent_retry",), ("extent_retry_rejected",))
    bad = deepcopy(init)
    bad.seg("_TEXT")[1].fixups[0].loc = 11
    real("N7", "Unsupported OMF loc 11 ptr16:32 fails closed", bad,
         "UNSUPPORTED", ("unsupported_construct",), ("unsupported_location",))
    bad = deepcopy(local)
    other_absolute = next(f for f in init.seg("_TEXT")[1].fixups
                          if not f.self_rel and f.offset != absolute.offset)
    hardcode_code(bad, other_absolute.offset)
    bad.segments[-1].fixups[0].target = pointers[1].target
    # Third independent defect: another ordinary byte, outside masked fields.
    bad.seg("_TEXT")[1].data[0] ^= 1
    real("N8", "Three independent code-byte, reverse-code and data-pointer defects", bad,
         "MISMATCH", ("code_bytes", "code_reloc_reverse", "data_reloc_forward"))

    # Boundary controls explicitly exercise branches absent from real controls.
    for kind in ("grp", "frame"):
        bad = deepcopy(init)
        bad.seg("_TEXT")[1].fixups[0].target_kind = kind
        real("B_"+kind, "Unsupported target kind "+kind, bad, "UNSUPPORTED",
             ("unsupported_construct",), ("unsupported_target",))
    bad = deepcopy(local)
    bad.segments[-1].fixups[0].self_rel = True
    real("B_data_self_rel", "Self-relative local data fixup is unsupported", bad,
         "UNSUPPORTED", ("unsupported_construct",), ("data_self_relative",))
    bad = deepcopy(choose)
    ss = bad.seg("_TEXT")[1]
    ss.fixups = [f for f in ss.fixups if f.offset != 0]
    _set32(ss.data, 0, p.fix_at[0x157d8][1])
    real("B_leading_reverse", "Leading original pointer lacks compiled fixup", bad,
         "MISMATCH", ("code_reloc_reverse",), src=choose_src)
    synth("B_intra_rel32", "Exact intra-_TEXT rel32 displacement needs no fixup",
          synthetic(b"\xe8\x01\x00\x00\x00\xc3\xc3",
                    publics={"Probe_": (1, 0), "Sibling_": (1, 6)}), "MATCH")
    synth("B_intra_rel8", "Exact intra-_TEXT rel8 displacement needs no fixup",
          synthetic(b"\xeb\x00\xc3"), "MATCH")
    synth("B_external_hardcoded_rel32", "Numerically correct external rel32 lacks FIXUPP",
          synthetic(b"\xe8\x20\x00\x00\x00\xc3"), "MISMATCH",
          ("code_reloc_reverse",), ("missing_compiled_relative_fixup",))
    synth("B_extent_filler", "Pure final alignment filler may be trimmed",
          synthetic(b"\xc3\x90\x90", fn_end=1, original=b"\xc3\x40\x40"), "MATCH")
    tail_fix = omf.Fixup(1, 9, False, "ext", "Probe_", 0)
    synth("B_extent_fixup", "Filler tail containing a FIXUPP cannot be trimmed",
          synthetic(b"\xc3\x00\x00\x00\x00", [tail_fix], fn_end=1,
                    original=b"\xc3\x40\x40\x40\x40"), "MISMATCH",
          ("extent_retry",), ("extent_retry_rejected",))
    # A straddling OMF field must also block retry, not merely one starting in tail.
    synth("B_extent_overlap", "FIXUPP straddling body/tail cannot be hidden",
          synthetic(b"\x90\x00\x00\x00\x00\x00", [tail_fix], fn_end=3,
                    original=b"\x90\x40\x40\x40\x40\x40"), "MISMATCH",
          ("extent_retry",), ("extent_retry_rejected",))
    # Code fixups anchor a second data segment; its pointers target _TEXT and
    # the first segment. Both segment targets must be resolved, not just ext.
    bad = deepcopy(local)
    tt, ds = bad.seg("_TEXT")[1], bad.segments[-1]
    for ptr in ds.fixups:
        target_addr = db[ptr.target]["addr"]
        ptr.target_kind, ptr.target = "seg", bad.seg("_TEXT")[0]
        _set32(ds.data, ptr.offset, target_addr-init_base)
    real("B_data_to_text", "Data pointer relocations resolve segment _TEXT targets", bad, "MATCH")
    bad = deepcopy(local)
    # Anchor a second DATA segment transitively through the original pointer
    # table's first entry, and compare its actual pointed-to code bytes.
    first_target = p.fix_at[table_base][1]
    target_obj = p.le.obj_at(first_target)
    target_data = p.image[target_obj.index][first_target-target_obj.base:first_target-target_obj.base+1]
    bad.segments.append(omf.Segment("EXTRA", "DATA", 1, 1, bytearray(target_data)))
    ptr = bad.segments[-2].fixups[0]
    ptr.target_kind, ptr.target = "seg", len(bad.segments)
    real("B_data_chain", "Local pointer resolves another transitively anchored segment", bad, "MATCH")
    bad = deepcopy(init)
    bad.segments.append(omf.Segment("$$SYMBOLS", "DEBSYM", 1, 4, bytearray(4),
                                   [omf.Fixup(0, 9, False, "seg", 1, 0)]))
    bad.segments.append(omf.Segment("$$TYPES", "DEBTYP", 1, 4, bytearray(4)))
    real("B_debug_metadata", "Non-loadable Watcom debug records are outside runtime image", bad, "MATCH")
    bad = deepcopy(init)
    bad.segments.append(omf.Segment("MYSTERY", "DATA", 1, 4, bytearray(4)))
    real("B_unanchored_data", "Unanchored nonempty runtime data cannot match", bad, "UNSUPPORTED",
         ("unsupported_construct",), ("unanchored_local_segment",))
    bad = deepcopy(local)
    bad.segments[-1].fixups[0].loc = 11
    real("B_data_location", "Unsupported local data pointer location", bad, "UNSUPPORTED",
         ("unsupported_construct",), ("unsupported_location",))
    bad = deepcopy(local)
    bad.segments[-1].fixups[0].target_kind = "frame"
    real("B_data_frame", "Unsupported local data pointer target kind", bad, "UNSUPPORTED",
         ("unsupported_construct",), ("unsupported_target",))
    bad = deepcopy(init)
    bad.seg("_TEXT")[1].fixups[0].loc = 99
    real("B_unknown_location", "Unknown relocation location fails closed without parser size assumption", bad,
         "UNSUPPORTED", ("unsupported_construct",), ("unsupported_location",))
    bad = deepcopy(init)
    next(f for f in bad.seg("_TEXT")[1].fixups if f.offset == absolute.offset).disp += 1
    real("B_wrong_addend", "Correct symbol with wrong explicit addend", bad, "MISMATCH",
         ("code_reloc_forward",), ("relocation_target_mismatch",))
    bad = deepcopy(choose)
    bad.seg("_TEXT")[1].fixups = [f for f in bad.seg("_TEXT")[1].fixups if f.offset != 0]
    _set32(bad.seg("_TEXT")[1].data, 0, p.fix_at[0x157d8][1]+1)
    real("B_leading_byte", "Unmasked leading byte corruption is compared", bad, "MISMATCH",
         ("code_bytes", "code_reloc_reverse"), src=choose_src)
    sp, sm, sd = synthetic(b"\xc3\x90\xc3", publics={"Probe_": (1, 0), "Sibling_": (1, 2)})
    sd["Sibling_"]["addr"] += 1
    synth("B_public_disagreement", "All public offsets must agree on region base", (sp, sm, sd),
          "MISMATCH", ("leading_bytes",), ("public_layout_mismatch",))
    synth("B_prefixed_branch", "Operand-size-prefixed direct rel16 is outside normalized support",
          synthetic(b"\x66\xe8\x00\x00\xc3"), "UNSUPPORTED",
          ("unsupported_construct",), ("unsupported_branch_encoding",))
    bad = deepcopy(init)
    ordinary = p.fix_at[init_base+absolute.offset][1]
    assert not any(a <= ordinary < a+f.size for a, (f, _) in p.fix_at.items())
    oo = p.le.obj_at(ordinary)
    original_byte = p.image[oo.index][ordinary-oo.base]
    si = len(bad.segments)+1
    cf = next(f for f in bad.seg("_TEXT")[1].fixups if f.offset == absolute.offset)
    cf.target_kind, cf.target, cf.disp = "seg", si, 0
    _set32(bad.seg("_TEXT")[1].data, cf.offset, 0)
    bad.segments.append(omf.Segment("_DATA", "DATA", 1, 1, bytearray([original_byte])))
    real("B_data_bytes_match", "Ordinary local data bytes are checked at their inferred anchor", bad, "MATCH")
    bad = deepcopy(bad)
    bad.segments[-1].data[0] ^= 1
    real("B_data_byte_corrupt", "Non-pointer byte in local data differs", bad, "MISMATCH",
         ("data_bytes",), ("byte_mismatch",))

    # Review Round 1: complete body coverage, retained branch closure, local
    # definitions, executable segments, and validation before extent filtering.
    bad = deepcopy(init)
    ss = bad.seg("_TEXT")[1]
    assert ss.data[-1] == 0xc3
    ss.data.pop()
    ss.length -= 1
    real("R1_truncated_ret", "Real InitPaths missing its final ret", bad, "MISMATCH",
         ("extent_retry",), ("truncated_function",), function="MISMATCH")
    synth("R1_truncated_instruction", "Compiled body ends inside mov eax,imm32",
          synthetic(b"\xb8\x01\x00", original=b"\xb8\x01\x00\x00\x00\xc3"),
          "MISMATCH", ("extent_retry",), ("truncated_function", "truncated_instruction"))
    for bits, jump in ((8, b"\xeb\x00"), (32, b"\xe9\x00\x00\x00\x00")):
        synth(f"R2_trimmed_rel{bits}", f"rel{bits} jump targets excluded final filler byte",
              synthetic(jump+b"\x90", fn_end=len(jump), original=jump+b"\xc3"),
              "MISMATCH",
              ("extent_retry",), ("trimmed_branch_target",))
        cases[-1].expected_function = "UNSUPPORTED" if bits == 8 else "MISMATCH"
    # Even an explicit relocation must not authorize discarding its target.
    synth("R2_trimmed_rel32_fixup", "Relocated jump still targets proposed trimmed tail",
          synthetic(b"\xe9\x00\x00\x00\x00\x90",
                    [omf.Fixup(1, 9, True, "ext", "Tail_", 0)], fn_end=5,
                    original=b"\xe9\x00\x00\x00\x00\xc3"),
          "MISMATCH", ("extent_retry",), ("trimmed_branch_target",))
    cases[-1].db["Tail_"] = dict(addr=0x10005)
    # A branch in an earlier body must use the eventual region extent too.
    synth("R2_sibling_trimmed_rel32", "Earlier function jumps into trimmed last-function tail",
          synthetic(b"\xe9\x01\x00\x00\x00\xc3\x90", fn_end=6,
                    publics={"Probe_": (1, 0), "Sibling_": (1, 5)},
                    original=b"\xe9\x01\x00\x00\x00\xc3\x40"),
          "MISMATCH", ("extent_retry",), ("trimmed_branch_target",))
    for table in ("publics", "statics"):
        bad = deepcopy(init)
        ss = bad.seg("_TEXT")[1]
        target = next(f.target for f in ss.fixups if f.target_kind == "ext" and not f.self_rel)
        bad.segments.append(omf.Segment("$$SYMBOLS", "DEBSYM", 1, 4, bytearray(4)))
        getattr(bad, table)[target] = (len(bad.segments), 0)
        real("R3_metadata_"+table, "Referenced external defined in debug "+table, bad,
             "UNSUPPORTED", ("unsupported_construct",), ("runtime_reference_to_debug",),
             function="UNSUPPORTED")
        bad = deepcopy(local)
        # The code fixes CONST at table_base. Its local definition of the
        # referenced DB symbol has a different address from that anchor.
        ss = bad.seg("_TEXT")[1]
        cf = next(f for f in ss.fixups if f.offset == absolute.offset)
        cf.target_kind, cf.target = "ext", absolute.target
        getattr(bad, table)[absolute.target] = (data_si, 0)
        real("R3_conflicting_"+table, "Local DATA definition disagrees with database "+table,
             bad, "MISMATCH", ("code_reloc_forward",), ("local_definition_mismatch",),
             function="MISMATCH")
        bad = deepcopy(local)
        getattr(bad, table)[absolute.target] = (data_si, 0)
        real("R3_unreferenced_"+table, "Unreferenced DATA definition contradicts database "+table,
             bad, "MISMATCH", ("code_reloc_forward",), ("local_definition_mismatch",),
             function="MATCH")
        # Matching local externals propagate anchors, with a nonzero symbol
        # offset and without requiring the symbol to exist in the database.
        bad = deepcopy(local)
        cf = next(f for f in bad.seg("_TEXT")[1].fixups if f.offset == absolute.offset)
        cf.target_kind, cf.target = "ext", "LocalTable"
        cf.disp -= 4
        getattr(bad, table)["LocalTable"] = (data_si, 4)
        real("R3_local_chain_"+table, "Local external propagates segment anchor "+table,
             bad, "MATCH", function="MATCH")
        bad = deepcopy(local)
        first_target = p.fix_at[table_base][1]
        target_obj = p.le.obj_at(first_target)
        target_byte = p.image[target_obj.index][first_target-target_obj.base]
        bad.segments.append(omf.Segment("EXTRA", "DATA", 1, 1, bytearray([target_byte])))
        bad.segments[data_si-1].fixups[0].target = "LocalByte"
        getattr(bad, table)["LocalByte"] = (len(bad.segments), 0)
        real("R3_transitive_"+table, "Local data external propagates a second anchor "+table,
             bad, "MATCH", function="MATCH")
    # Use an independent original for an anchored extra executable call so its
    # missing relocation cannot be hidden by code=False data-byte checking.
    pp, mm, dd = synthetic(b"\xb8\x00\x00\x00\x00\xc3",
                          [omf.Fixup(1, 9, False, "seg", 2, 0)], fn_end=6,
                          original=b"\xb8\x06\x00\x01\x00\xc3\xe8\x20\x00\x00\x00",
                          original_fixes=[(1, 0x10006)])
    mm.segments.append(omf.Segment("EXTRA_TEXT", "CODE", 1, 5,
                                    bytearray(b"\xe8\x20\x00\x00\x00")))
    synth("R4_extra_code", "Anchored additional CODE call lacks external rel32 fixup",
          (pp, mm, dd), "UNSUPPORTED", ("unsupported_construct",), ("additional_code_segment",))
    for off in (1, -6):
        synth("R5_oob_end" if off == 1 else "R5_oob_negative",
              "Entirely out-of-bounds unsupported fixup must be validated",
              synthetic(b"\xc3", [omf.Fixup(off, 11, False, "grp", 99, 0)]),
              "UNSUPPORTED", ("unsupported_construct",),
              ("fixup_out_of_bounds", "unsupported_location", "unsupported_target"))
    return cases


def evaluate_control(c, index=None):
    result = match_module(c.p, c.mod, c.db, index)
    try:
        legacy = match.match_module(c.p, c.mod, c.db)
        legacy_verdict = "MATCH" if legacy and all(x[1] == "MATCH" for x in legacy) else "MISMATCH"
    except Exception as exc:
        legacy = [["exception", "ERROR", [f"{type(exc).__name__}: {exc}"]]]
        legacy_verdict = "ERROR"
    findings = result["region"]["findings"]
    # Extent evidence is a function concern even if region ordinary-byte
    # checks independently reject the same unsafe object.
    for fr in result["functions"].values():
        for f in fr["findings"]:
            if f not in findings:
                findings.append(f)
    cats = {f["category"] for f in findings}
    codes = {f["code"] for f in findings}
    fv = [r["verdict"] for r in result["functions"].values()]
    passed = (result["region"]["verdict"] == c.expected and
              set(c.required_categories) <= cats and set(c.required_codes) <= codes and
              (c.expected_function is None or all(v == c.expected_function for v in fv)))
    return dict(id=c.id, description=c.description, expected=c.expected, passed=passed,
                legacy_verdict=legacy_verdict, legacy_results=legacy,
                e0_function_verdicts=fv, e0_region_verdict=result["region"]["verdict"],
                required_categories=list(c.required_categories), required_codes=list(c.required_codes),
                findings=findings, metrics=result["region"]["metrics"], provenance=c.provenance)


def run_controls():
    cases = build_controls()
    indexes = {}
    rows = []
    for c in cases:
        if id(c.p) not in indexes:
            indexes[id(c.p)] = OriginalIndex(c.p)
        rows.append(evaluate_control(c, indexes[id(c.p)]))
    return dict(total=len(rows), passed=sum(r["passed"] for r in rows),
                failed=sum(not r["passed"] for r in rows), controls=rows)
